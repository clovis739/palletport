/** Trim to ≤ max chars at a word boundary (adds an ellipsis when cut). */
export function trimDescription(text: string | null | undefined, max = 155) {
  const clean = (text ?? "").replace(/\s+/g, " ").trim();
  if (clean.length <= max) return clean;
  const cut = clean.slice(0, max - 1);
  const at = cut.lastIndexOf(" ");
  return `${(at > 60 ? cut.slice(0, at) : cut).replace(/[\s,;:.\-–—]+$/, "")}…`;
}

/**
 * Per-page metadata. Keep `title` ≤ ~60 characters including the " · PalletPort" suffix the root template adds
 * (so aim for ≤ 47 characters here), and write the description for a buyer, not a search engine.
 */
export async function pageMetadata({
  title,
  description,
  path,
  image,
  imageAlt,
  type = "website",
  noIndex = false,
  absoluteTitle = false,
  publishedTime,
  modifiedTime,
  authors,
}: {
  title: string;
  description?: string;
  path: string;
  image?: string;
  imageAlt?: string;
  type?: "website" | "article";
  noIndex?: boolean;
  /** Use the title as-is, without the " · PalletPort" template. */
  absoluteTitle?: boolean;
  publishedTime?: string;
  modifiedTime?: string;
  authors?: string[];
}): Promise<Metadata> {
  // Brand name from Admin → Business profile; text written with the original name follows a rename.
  const { getBrand } = await import("@/lib/brand");
  const brand = await getBrand();
  title = rebrandText(title, brand);
  description = description ? rebrandText(description, brand) : description;
  if (imageAlt) imageAlt = rebrandText(imageAlt, brand);
  const desc = description ? trimDescription(description) : undefined;
  const fullTitle = absoluteTitle || title.includes(brand) ? title : `${title} · ${brand}`;
  const img = { url: image ?? DEFAULT_OG_IMAGE, width: 1200, height: 630, alt: imageAlt ?? fullTitle };
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description: desc,
    alternates: { canonical: path },
    openGraph: {
      siteName: brand,
      locale: "en_US",
      url: path,
      title: fullTitle,
      description: desc,
      images: [img],
      ...(type === "article" ? { type: "article" as const, publishedTime, modifiedTime, authors } : { type: "website" as const }),
    },
    twitter: { card: "summary_large_image", title: fullTitle, description: desc, images: [img.url] },
    // Public-but-thin pages (e.g. search results): keep out of the index but let crawlers follow the lot links.
    ...(noIndex ? { robots: { index: false, follow: true, googleBot: { index: false, follow: true } } } : {}),
  };
}

/** Absolute-or-root URL for a social image ref (stock key, media URL or https URL); "" → the generated OG image. */
export function ogImageUrl(ref: string | null | undefined) {
  const img = resolveImageRef(ref);
  if (img.kind === "stock") return photoSrc(img.photo, 1200, 1200 / 630);
  if (img.kind === "url") return img.src;
  return DEFAULT_OG_IMAGE;
}

