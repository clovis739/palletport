/**
 * SEO + structured data helpers.
 *
 * Rule of thumb: only describe what is TRUE and VISIBLE on the page. No invented phone numbers, addresses,
 * hours, ratings or reviews. Business contact facts come from the `business` site settings (Admin → Site →
 * Business profile; pass them in — this module stays free of server-only imports) and the store record
 * (src/lib/store.ts). These OPTIONAL environment variables are fallbacks, emitted only when set:
 *
 *   APP_URL             Public base URL, e.g. https://www.example.com. Optional: without it the URL is worked out
 *                       automatically (hosting platform variables, then the request's own host, then the local
 *                       dev server's port). A localhost APP_URL is ignored in favour of the real address.
 *   STORE_NAME          Brand name used in metadata (fallback "PalletPort"; the DB store name is used in JSON-LD)
 *   STORE_PHONE         Customer-service phone, E.164 or display format, e.g. +1-614-555-0100
 *   STORE_EMAIL         Customer-service email
 *   STORE_STREET        Warehouse street address (only if buyers can visit / pick up there)
 *   STORE_POSTAL        Warehouse postal code
 *   STORE_COUNTRY       ISO country code for the address, e.g. US
 *   STORE_HOURS         Warehouse/pickup hours in schema.org format, e.g. "Mo-Fr 08:00-18:00" or "Mo-Fr 08:00-18:00; Sa 09:00-12:00"
 *   STORE_SAME_AS       Comma-separated official profile URLs (Google Business Profile, LinkedIn, Facebook, ...)
 *   ALLOW_AI_CRAWLERS   "false" disallows AI crawlers in robots.txt (default: allowed) — see src/app/robots.ts
 */
