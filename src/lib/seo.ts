// ---------- URLs ----------

const cleanUrl = (u: string) => u.trim().replace(/\/+$/, "");
const withProtocol = (host: string) => (/^https?:\/\//i.test(host) ? host : `https://${host}`);

/** True for http(s)://localhost, 127.0.0.1 or [::1], any port. */
export function isLocalUrl(u: string) {
  return /^https?:\/\/(localhost|127\.0\.0\.1|\[::1\])(:\d+)?(\/|$)/i.test(u);
}

/**
 * The public URL from configuration, or null: APP_URL (NEXT_PUBLIC_APP_URL also accepted), then the hosting
 * platform's own variable (Vercel, Netlify, Render, Railway, Fly). A localhost APP_URL doesn't count, so an old
 * "http://localhost:3000" in .env never overrides the port or domain the site is really served on.
 */
export function configuredSiteUrl(): string | null {
  const explicit = (process.env.APP_URL || process.env.NEXT_PUBLIC_APP_URL || "").trim();
  if (explicit && !isLocalUrl(explicit)) return cleanUrl(withProtocol(explicit));
  const env = process.env;
  const platform =
    env.VERCEL_PROJECT_PRODUCTION_URL ||
    (env.NETLIFY === "true" ? env.URL : "") ||
    env.RENDER_EXTERNAL_URL ||
    env.RAILWAY_PUBLIC_DOMAIN ||
    (env.FLY_APP_NAME ? `${env.FLY_APP_NAME}.fly.dev` : "") ||
    env.VERCEL_URL ||
    "";
  return platform ? cleanUrl(withProtocol(platform)) : null;
}

/**
 * Base URL of the site, without a trailing slash. Synchronous, for JSON-LD and helpers that can't await:
 * configured URL → the running Next.js server's own origin (right port in dev and `next start`) → localhost.
 * Server code that has a request should prefer `requestSiteUrl()` (src/lib/site-url.ts), which also knows the
 * host the visitor actually used.
 */
export function siteUrl() {
  return (
    configuredSiteUrl() ??
    cleanUrl(process.env.__NEXT_PRIVATE_ORIGIN || `http://localhost:${process.env.PORT || 3000}`)
  );
}

export function absoluteUrl(path = "/") {
  if (/^https?:\/\//i.test(path)) return path;
  return `${siteUrl()}${path.startsWith("/") ? "" : "/"}${path}`;
}

const ORG_ID = () => `${siteUrl()}/#organization`;
