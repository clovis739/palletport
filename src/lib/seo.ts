// ---------- Lot indexing rules (shared by lot metadata and the sitemap) ----------

/** Sold-out lots stay indexed this many days after the sale, then drop out (noindex + out of the sitemap). */
export const SOLD_INDEX_DAYS = 30;

type SoldLotLike = {
  createdAt: Date;
  /** Latest order line for the lot, newest first. */
  orderItems?: { order: { createdAt: Date } }[];
};

/** When a SOLD_OUT lot sold: its latest order, else the listing date. */
export function lotSoldAt(lot: SoldLotLike): Date {
  return lot.orderItems?.[0]?.order.createdAt ?? lot.createdAt;
}

/** ACTIVE lots are indexable; SOLD_OUT only within SOLD_INDEX_DAYS of the sale; DRAFT never. */
export function lotIndexable(lot: SoldLotLike & { status: string }, now = Date.now()): boolean {
  if (lot.status === "ACTIVE") return true;
  if (lot.status !== "SOLD_OUT") return false;
  return now - lotSoldAt(lot).getTime() <= SOLD_INDEX_DAYS * 86400000;
}

/** Prisma select for the latest order line of a lot (feeds lotSoldAt). */
export const LATEST_ORDER_SELECT = {
  select: { order: { select: { createdAt: true } } },
  orderBy: { order: { createdAt: "desc" as const } },
  take: 1,
};

