const ITEM_CONDITION: Record<string, string> = {
  NEW: "https://schema.org/NewCondition",
  SHELF_PULL: "https://schema.org/NewCondition",
  CUSTOMER_RETURN: "https://schema.org/UsedCondition",
  MIXED: "https://schema.org/UsedCondition",
  SALVAGE: "https://schema.org/DamagedCondition",
};

const AVAILABILITY: Record<string, string> = {
  ACTIVE: "https://schema.org/InStock",
  SOLD_OUT: "https://schema.org/SoldOut",
};

type LotForSchema = {
  id: string;
  slug: string;
  title: string;
  description: string;
  externalSku?: string | null;
  sku: string;
  condition: string;
  priceCents: number;
  msrpCents: number;
  units: number;
  palletCount: number;
  lotSize: string;
  weightLbs?: number;
  brand?: string;
  status: string;
  available?: number;
  images?: string | null;
  category?: { name: string } | null;
  subcategory?: { name: string } | null;
};

const dollars = (cents: number) => (cents / 100).toFixed(2);

/** The "Lot #" shown on lot pages. */
export const lotNumber = (lot: { id: string }) => lot.id.slice(-6).toUpperCase();

export function productJsonLd(lot: LotForSchema, sellerName = SITE_NAME): Json {
  const url = absoluteUrl(`/lots/${lot.slug}`);
  // Only real uploaded photos describe the product. Stock photos are illustrative, so they're left out.
  const images = parseImages(lot.images).map((src) => absoluteUrl(src));
  const props: Json[] = [
      ...(lot.units > 0 ? [{ "@type": "PropertyValue", name: "Units", value: lot.units }] : []),
    { "@type": "PropertyValue", name: "Lot size", value: LOT_SIZES[lot.lotSize]?.label ?? lot.lotSize },
    ...(lot.lotSize === "CASE" ? [] : [{ "@type": "PropertyValue", name: "Pallets", value: lot.palletCount }]),
      ...(lot.msrpCents > 0 ? [{ "@type": "PropertyValue", name: "Estimated retail value", value: Number(dollars(lot.msrpCents)), unitText: "USD" }] : []),
    { "@type": "PropertyValue", name: "Condition grade", value: CONDITIONS[lot.condition]?.label ?? lot.condition },
  ];
  return {
    "@context": "https://schema.org",
    "@type": "Product",
    "@id": `${url}#product`,
    name: lot.title,
    description: lot.description,
    sku: lot.sku,
    url,
    category: lot.subcategory && lot.category ? `${lot.category.name} > ${lot.subcategory.name}` : lot.category?.name,
    brand: lot.brand ? { "@type": "Brand", name: lot.brand } : undefined,
    itemCondition: ITEM_CONDITION[lot.condition],
    image: images.length ? images : undefined,
    weight: lot.weightLbs ? { "@type": "QuantitativeValue", value: lot.weightLbs, unitCode: "LBR" } : undefined,
    additionalProperty: props,
    offers: {
      "@type": "Offer",
      url,
      priceCurrency: "USD",
      price: dollars(lot.priceCents),
      availability: AVAILABILITY[lot.status] ?? "https://schema.org/InStock",
      itemCondition: ITEM_CONDITION[lot.condition],
      seller: { "@type": "Organization", "@id": ORG_ID(), name: sellerName },
      ...(lot.status === "ACTIVE" && lot.available ? { inventoryLevel: { "@type": "QuantitativeValue", value: lot.available } } : {}),
    },
  };
}

type PostLike = { slug: string; title: string; excerpt: string; date?: string; updated?: string; category?: string; tags?: string[] };

export function articleJsonLd(post: PostLike, opts: { authorName: string; image?: string; path?: string }): Json {
  const url = absoluteUrl(opts.path ?? `/blog/${post.slug}`);
  return {
    "@context": "https://schema.org",
    "@type": "BlogPosting",
    headline: post.title,
    description: post.excerpt,
    datePublished: post.date,
    dateModified: post.updated ?? post.date,
    // Bylines on this site are team names, so the author is an Organization rather than a Person.
    author: { "@type": "Organization", name: opts.authorName, url: `${siteUrl()}/about` },
    publisher: { "@id": ORG_ID() },
    mainEntityOfPage: { "@type": "WebPage", "@id": url },
    url,
    image: opts.image ? [opts.image] : undefined,
    articleSection: post.category,
    keywords: post.tags?.length ? post.tags.join(", ") : undefined,
    inLanguage: "en-US",
  };
}

/** Only use where the questions AND answers are visible on the page. */
export function faqJsonLd(items: { q: string; a: string }[]): Json | null {
  const list = items.filter((i) => i.q.trim() && i.a.trim());
  if (!list.length) return null;
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: list.map((i) => ({ "@type": "Question", name: i.q, acceptedAnswer: { "@type": "Answer", text: i.a } })),
  };
}

export function itemListJsonLd(name: string, lots: { slug: string; title: string }[]): Json {
  return {
    "@context": "https://schema.org",
    "@type": "ItemList",
    name,
    numberOfItems: lots.length,
    itemListElement: lots.map((l, i) => ({ "@type": "ListItem", position: i + 1, url: absoluteUrl(`/lots/${l.slug}`), name: l.title })),
  };
}

/** Plain-text of an Article body (used for FAQ answers, which must match the visible text). */
export function sectionsText(body: { p?: string[]; list?: string[] }[]) {
  return body.flatMap((s) => [...(s.p ?? []), ...(s.list ?? [])]).join(" ").replace(/\s+/g, " ").trim();
}

